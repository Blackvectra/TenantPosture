# NIST 800-53 control-family rollup sheet.
# The 'NIST 800-53' sheet above lists findings; this one aggregates them by
# 800-53 control FAMILY, which is the unit an 800-53 / FedRAMP / CMMC reader
# organizes their own POA&M around. A finding citing controls in two families
# counts in both, so Assessed does not sum to the assessment total.
NIST_FAMILY_NAMES = {
    'AC':'Access Control','AT':'Awareness and Training','AU':'Audit and Accountability',
    'CA':'Assessment, Authorization, and Monitoring','CM':'Configuration Management',
    'CP':'Contingency Planning','IA':'Identification and Authentication',
    'IR':'Incident Response','MA':'Maintenance','MP':'Media Protection',
    'PE':'Physical and Environmental Protection','PL':'Planning',
    'PM':'Program Management','PS':'Personnel Security',
    'PT':'PII Processing and Transparency','RA':'Risk Assessment',
    'SA':'System and Services Acquisition','SC':'System and Communications Protection',
    'SI':'System and Information Integrity','SR':'Supply Chain Risk Management',
}
NIST_REF_RE = re.compile(r'^([A-Z]{2})-(\d{1,3})(\(\d{1,3}\))?$')

fam_findings = {}
fam_refs     = {}
for f in scoring:
    raw = f.get('NIST','') or ''
    fams_here, refs_here = set(), set()
    for tok in str(raw).split(','):
        m = NIST_REF_RE.match(tok.strip())
        if not m: continue
        fams_here.add(m.group(1))
        refs_here.add('%s-%d%s' % (m.group(1), int(m.group(2)), m.group(3) or ''))
    for fam in fams_here:
        fam_findings.setdefault(fam, []).append(f)
        fam_refs.setdefault(fam, set()).update(
            r for r in refs_here if r.split('-')[0] == fam)

nist_fam_rows = []
for fam in sorted(fam_findings):
    grp   = fam_findings[fam]
    sat   = sum(1 for x in grp if x['State'] == 'Satisfied')
    part  = sum(1 for x in grp if x['State'] == 'Partial')
    gap   = sum(1 for x in grp if x['State'] == 'Gap')
    na    = sum(1 for x in grp if x['State'] == 'NotApplicable')
    err   = sum(1 for x in grp if x['State'] == 'Error')
    # Same denominator rule as Get-NRGCoverageScore -ErrorHandling Gap:
    # NotApplicable is excluded, Error counts as a soft gap.
    scored = len(grp) - na
    # A family assessed only through NotApplicable findings has no denominator.
    # Report that as "Not assessed", never as 0% — 0% is a failing grade for a
    # question the tool never got to ask.
    cov    = ('%d%%' % round(100.0 * (sat + 0.5 * part) / scored)) if scored > 0 else 'Not assessed'
    nist_fam_rows.append({
        'Family': fam,
        'Family Name': NIST_FAMILY_NAMES.get(fam, fam),
        'Assessed': len(grp), 'Met': sat, 'Partial': part, 'Gap': gap,
        'N/A': na, 'Error': err, 'Coverage': cov,
        '800-53 Controls': '; '.join(nist_label(x) for x in sorted(fam_refs.get(fam, set()))),
    })
if nist_fam_rows:
