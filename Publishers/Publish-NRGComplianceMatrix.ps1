#Requires -Version 7.0
#
# Publish-NRGComplianceMatrix.ps1  (v4.5.5)
# Generates a professional XLSX compliance matrix from assessment findings.
#
# Sheets:
#   1. Summary        — Overall posture, score, workload breakdown, framework scores
#   2. All Controls   — Every control with status, severity, framework citations
#   3. Gaps Only      — Filtered to Gap/Partial, with remediation commands
#   4. CIS M365 v6    — Controls mapped to CIS sections
#   5. CISA SCuBA     — Controls mapped to SCuBA policy IDs
#   6. NIST 800-53    — Controls mapped to NIST control families
#   7. CMMC 2.0       — Controls mapped to CMMC practices
#   8. ISO 27001      — Controls mapped to ISO 27001:2022 clauses
#   9. SOC 2          — Controls mapped to Trust Services Criteria
#  10. HIPAA          — Controls mapped to HIPAA §164 safeguards
#  11. NIST Physical & Device — Physical/media/maintenance 800-53 controls, with
#                        implementation options and the evidence an assessor must
#                        collect off-tenant. Unscored by design.
#  12. NIST Families  — Coverage rolled up by 800-53 control family (AC/AU/IA/...)
#  13. License Gaps   — Controls blocked by current license tier
#
# The XLSX is generated by calling an embedded Python script that uses openpyxl.
# This avoids requiring Excel or COM automation on the assessment machine.
#
# SECURITY: No tenant data is interpolated into Python code.
#           All data passes through JSON serialization → Python reads the JSON.
#

function Publish-NRGComplianceMatrix {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)] [hashtable] $Metadata,
        [Parameter(Mandatory)] [object[]]  $Findings,
        [Parameter(Mandatory)]
        [ValidateScript({
            if ($_ -match '\.\.[\\\/]') { throw 'Path traversal not allowed.' }
            return $true
        })]
        [string] $OutputPath
    )

    # Verify Python + openpyxl available
    $pythonCmd = $null
    foreach ($py in @('python3','python')) {
        try {
            $null = & $py -c 'import openpyxl' 2>&1
            if ($LASTEXITCODE -eq 0) { $pythonCmd = $py; break }
        } catch { }
    }
    if (-not $pythonCmd) {
        Write-Warning "openpyxl not available — skipping XLSX output. Install: pip install openpyxl"
        return
    }

    # Load control definitions for framework citations + license info
    $cdefs = @{}
    try { foreach ($c in (Get-NRGControlDefinitions)) { $cdefs[$c.ControlId] = $c } } catch { }

    # Official 800-53 Rev 5 titles for every identifier any control cites,
    # passed through the payload rather than duplicated in the embedded Python.
    # The family NAMES below are hardcoded on the Python side and that is
    # already a duplication; adding 77 control titles beside them would be a
    # second copy of Config/nist-800-53-catalog.json that rots independently of
    # the real one. Sourced here from the same catalog the standalone NIST
    # matrix uses, so the two deliverables cannot disagree about what AC-2 is.
    $nistTitles = @{}
    if (Get-Command Get-NRGNISTControlTitle -ErrorAction SilentlyContinue) {
        foreach ($c in $cdefs.Values) {
            $ref = [string](Get-NRGNestedProperty -Object $c -Path 'References.NIST' -Default '')
            # No trailing \b: after the ')' of an enhancement there is no
            # word boundary, so '\b[A-Z]{2}-\d+(\(\d+\))?\b' matches only
            # 'IA-2' out of 'IA-2(1)' and silently drops every enhancement.
            foreach ($m in [regex]::Matches($ref, '\b[A-Z]{2}-\d+(?:\(\d+\))?')) {
                $nid = $m.Value
                if ($nistTitles.ContainsKey($nid)) { continue }
                $t = [string](Get-NRGNISTControlTitle -ControlId $nid)
                # Only real titles. A lookup that echoes the identifier back is
                # a miss, and storing it would render "AC-2 AC-2" in the sheet.
                if ($t -and $t -ne $nid) { $nistTitles[$nid] = $t }
            }
        }
    }

    # Build serializable data payload
    $matrixLicProfile = $null
    if (Get-Command Get-NRGTenantLicenseProfile -ErrorAction SilentlyContinue) {
        try { $matrixLicProfile = Get-NRGTenantLicenseProfile } catch { $matrixLicProfile = $null }
    }
    $matrixLicKnown = [bool](Get-NRGObjectField -Item $matrixLicProfile -Key 'HasLicenseData' -Default $false)
    $payload = @{
        NistTitles = $nistTitles
        # Get-NRGObjectField, not dot-access-then-??: under StrictMode a missing
        # key THROWS before ?? can supply the default, so `$Metadata.Operator ??
        # ''` aborts the whole publisher whenever Operator is absent. It is
        # absent on the -FromResults replay path, whose fallback metadata carries
        # only TenantDomain / AssessmentDate / ToolVersion — and the caller wraps
        # this in a try/catch that degrades to a warning, so the XLSX silently
        # was not produced rather than failing loudly.
        Metadata = @{
            TenantDomain   = [string](Get-NRGObjectField -Item $Metadata -Key 'TenantDomain'   -Default 'Unknown')
            AssessmentDate = [string](Get-NRGObjectField -Item $Metadata -Key 'AssessmentDate' -Default (Get-Date -Format 'yyyy-MM-dd'))
            ToolVersion    = [string](Get-NRGObjectField -Item $Metadata -Key 'ToolVersion'    -Default '4.5.5')
            Operator       = [string](Get-NRGObjectField -Item $Metadata -Key 'Operator'       -Default '')
        }
        Findings = @($Findings | ForEach-Object {
            $ctrl = $cdefs[$_.ControlId]
            $licReqStr = [string](Get-NRGObjectField -Item $ctrl -Key 'LicenseRequirement' -Default 'Included')
            @{
                ControlId       = [string]$_.ControlId
                Title           = [string]$_.Title
                Category        = [string]$_.Category
                State           = [string]$_.State
                Severity        = [string]$_.Severity
                Detail          = [string]$_.Detail
                CurrentValue    = [string](Get-NRGObjectField -Item $_ -Key 'CurrentValue'  -Default '')
                RequiredValue   = [string](Get-NRGObjectField -Item $_ -Key 'RequiredValue' -Default '')
                Remediation     = [string]$(
                    # Get-NRGObjectField, not dot-access-then-??: $ctrl is the
                    # controls.json definition and $_ is the finding — either can
                    # be a replayed/deserialized object that predates this field,
                    # and under StrictMode a missing member throws before ?? can
                    # apply (the "XLSX publish failed: Remediation cannot be
                    # found" warning on every run).
                    $rem = Get-NRGObjectField -Item $ctrl -Key 'Remediation' -Default ''
                    if (-not $rem) { $rem = Get-NRGObjectField -Item $_ -Key 'Remediation' -Default '' }
                    $rem
                )
                # $ctrl is $null for DEV-* endpoint findings (device-controls.json,
                # not controls.json), and under StrictMode Latest a member read on
                # $null throws before ?? applies — which aborted the whole XLSX.
                BusinessRisk    = [string](Get-NRGObjectField -Item $ctrl -Key 'BusinessRisk' -Default '')
                LicenseReq      = $licReqStr
                # The License Gaps sheet lists only controls whose license the
                # tenant does NOT hold, decided by the same per-control test the
                # score uses. It listed every Gap with a non-"Included"
                # requirement, so a Business Premium tenant was told it lacked
                # Business Premium. Unknown licensing blocks nothing.
                LicenseBlocked  = [bool]($matrixLicKnown -and $licReqStr -notmatch '^Included' -and
                                   -not (Test-NRGLicenseRequirementMet -LicenseRequirement $licReqStr -LicenseProfile $matrixLicProfile -ControlId ([string]$_.ControlId)))
                FrameworkIds    = @(Get-NRGObjectField -Item $_ -Key 'FrameworkIds' -Default @() | ForEach-Object { [string]$_ })
                CIS             = [string](Get-NRGNestedProperty -Object $ctrl -Path 'References.CIS'      -Default '')
                SCuBA           = [string](Get-NRGNestedProperty -Object $ctrl -Path 'References.SCuBA'    -Default '')
                NIST            = [string](Get-NRGNestedProperty -Object $ctrl -Path 'References.NIST'     -Default '')
                CMMC            = [string](Get-NRGNestedProperty -Object $ctrl -Path 'References.CMMC'     -Default '')
                ISO27001        = [string](Get-NRGNestedProperty -Object $ctrl -Path 'References.ISO27001' -Default '')
                SOC2            = [string](Get-NRGNestedProperty -Object $ctrl -Path 'References.SOC2'     -Default '')
                HIPAA           = [string](Get-NRGNestedProperty -Object $ctrl -Path 'References.HIPAA'    -Default '')
                PCIDSS          = [string](Get-NRGNestedProperty -Object $ctrl -Path 'References.PCIDSS'   -Default '')
                DISASTIG        = [string](Get-NRGNestedProperty -Object $ctrl -Path 'References.DISASTIG' -Default '')
                MITRE           = [string]((Get-NRGNestedProperty -Object $ctrl -Path 'References.MITRE' -Default @()) -join ', ')
            }
        })
    }

    # Physical / media / device 800-53 controls. This is the sheet an assessor
    # actually works down while collecting off-tenant evidence, so it belongs in
    # the spreadsheet deliverable rather than only in the HTML report. Flattened
    # here (not in Python) so the scope and status semantics have exactly one
    # implementation — Lib/Get-NRGNISTPhysicalPosture.ps1.
    $payload.NistPhysical = @()
    if (Get-Command Get-NRGNISTPhysicalPosture -ErrorAction SilentlyContinue) {
        try {
            $phys = Get-NRGNISTPhysicalPosture -Findings $Findings
            if ($phys -and $phys.Available) {
                $payload.NistPhysical = @(foreach ($grp in $phys.Groups) {
                    foreach ($it in $grp.Items) {
                        @{
                            Group             = [string]$grp.Title
                            NistControl       = [string]$it.NistControl
                            NistTitle         = [string]$it.NistTitle
                            Scope             = [string]$it.Scope
                            Status            = [string]$it.Status
                            DeviceAspect      = [string]$it.DeviceAspect
                            Evidence          = [string](@($it.Evidence | ForEach-Object { "$($_.ControlId) ($($_.State))" }) -join ', ')
                            OffTenantEvidence = [string]$it.OffTenantEvidence
                            Options           = [string](@($it.Options) -join "`n")
                        }
                    }
                })
            }
        } catch {
            Write-Verbose "NIST physical posture unavailable for the matrix: $($_.Exception.Message)"
        }
    }

    # Serialize JSON for the Python helper.
    # Audit fix (v4.6.x MED #4): the previous implementation wrote tenant
    # findings to $env:TEMP via [System.IO.Path]::GetTempFileName(), which
    # creates the file with default inherited permissions before any ACL
    # tightening can run. Two-step (create + chmod) is race-prone in a
    # shared TEMP. Instead, co-locate the helper JSON next to the XLSX
    # output (which already lives in the ACL-hardened output directory)
    # and harden it via Set-NRGSensitiveFileAcl as soon as we write it.
    $outputDir = Split-Path -Parent $OutputPath
    if (-not $outputDir -or -not (Test-Path -LiteralPath $outputDir)) {
        $outputDir = [System.IO.Path]::GetTempPath()
    }
    $matrixBase = [System.IO.Path]::GetFileNameWithoutExtension($OutputPath)
    if ([string]::IsNullOrWhiteSpace($matrixBase)) { $matrixBase = 'compliance-matrix' }
    $tmpJson = Join-Path $outputDir "$matrixBase-matrix-input.json"
    try {
        # Publisher self-hardens via Set-NRGSensitiveFileContent: the file is
            # pre-created and its ACL applied BEFORE tenant data lands. Writing with a
            # bare Out-File lets the file inherit the parent directory ACL for the
            # duration of the write, which on a shared MSP workstation or a synced
            # OneDrive folder is a window in which a co-resident process can read CA
            # policies, admin UPNs, OAuth grants and DMARC records. Hardening travels
            # with the terminal write so no caller can forget it. The Out-File fallback
            # preserves behavior if Lib/ has not been dot-sourced.
        if (Get-Command Set-NRGSensitiveFileContent -ErrorAction SilentlyContinue) {
            Set-NRGSensitiveFileContent -Path $tmpJson -Content ($payload | ConvertTo-Json -Depth 6 -Compress)
        } else {
            $payload | ConvertTo-Json -Depth 6 -Compress | Out-File -LiteralPath $tmpJson -Encoding utf8
            if (Get-Command Set-NRGSensitiveFileAcl -ErrorAction SilentlyContinue) {
                Set-NRGSensitiveFileAcl -Path $tmpJson -ErrorAction SilentlyContinue
            }
        }
        if (Get-Command Set-NRGSensitiveFileAcl -ErrorAction SilentlyContinue) {
            Set-NRGSensitiveFileAcl -Path $tmpJson -ErrorAction SilentlyContinue
        }

        # Embedded Python — reads JSON, writes XLSX, no string interpolation of tenant data
        $pyScript = @'
import json, re, sys, os
from openpyxl import Workbook
from openpyxl.styles import (Font, PatternFill, Alignment, Border, Side,
                              GradientFill)
from openpyxl.utils import get_column_letter

data_path = sys.argv[1]
out_path  = sys.argv[2]

with open(data_path, encoding='utf-8') as f:
    d = json.load(f)

# Official Rev 5 control titles, supplied by the PowerShell side from
# Config/nist-800-53-catalog.json. A bare "AC-2, AC-3" only tells a reader
# which controls were exercised if they already know 800-53 by heart.
NIST_TITLES = d.get('NistTitles', {}) or {}

def nist_label(nid):
    """'AC-2 Account Management', or the bare id when the catalog has no
    entry. A missing title must never delete the identifier from the row."""
    t = NIST_TITLES.get(nid, '')
    return ('%s %s' % (nid, t)) if t else nid


meta     = d['Metadata']
findings = d['Findings']
# One verdict per control for every SCORE on this workbook (worst instance:
# Gap > Error > Partial > Satisfied > NotApplicable), matching
# Get-NRGCoverageScore. DNS emits one finding per domain; scoring each would
# weight a DNS control once per domain. Row listings still use `findings`.
_rank = {'Gap': 5, 'Error': 4, 'Partial': 3, 'Satisfied': 2, 'NotApplicable': 1}
_worst = {}
for _f in findings:
    _c = _f.get('ControlId', '')
    if _c not in _worst or _rank.get(_f['State'], 0) > _rank.get(_worst[_c]['State'], 0):
        _worst[_c] = _f
scoring = list(_worst.values())

# ── Color palette ─────────────────────────────────────────────────────────────
NAVY    = '0F2544'
ORANGE  = 'E8621A'
BLUE    = '3B7DD8'
WHITE   = 'FFFFFF'
LGRAY   = 'F4F7FB'
MGRAY   = 'E2E8F0'
DGRAY   = '6B7280'
RED     = 'DC2626'
AMBER   = 'CA8A04'
GREEN   = '059669'
ROSE    = 'FEF2F2'
AMBER_L = 'FFFBEB'
GREEN_L = 'F0FDF4'
NA_L    = 'F9FAFB'

SEV_COLORS = {'Critical':'DC2626','High':'EA580C','Medium':'CA8A04','Low':'65A30D','Informational':'6B7280'}
STATE_COLORS = {'Gap':ROSE,'Partial':AMBER_L,'Satisfied':GREEN_L,'NotApplicable':NA_L}
STATE_FONT   = {'Gap':'991B1B','Partial':'92400E','Satisfied':'166534','NotApplicable':'6B7280'}

# CWE-345 / OWASP A03 — XLSX formula-injection guard. Finding fields
# (Detail, CurrentValue, Remediation, Title) can carry attacker-influenced
# strings — a value like "=cmd|'/c calc'!A1" written verbatim to a cell
# becomes a live formula when the operator opens the workbook. Prefix
# formula-leading cells with an apostrophe (Excel-standard neutralization)
# and force string data_type so openpyxl never auto-detects a formula.
_FORMULA_LEAD = ('=', '+', '-', '@', '\t', '\r')

def _safe(val):
    # Numeric values (including bool, which subclasses int) pass through
    # unchanged so Excel renders them as numbers — sorting, formatting,
    # and aggregation in the operator's workbook depend on it.
    if val is None: return ''
    if isinstance(val, (int, float)):
        return val
    s = str(val)
    if s and s[0] in _FORMULA_LEAD:
        return "'" + s
    return s

def hdr(ws, row, col, val, bg=NAVY, fg=WHITE, bold=True, wrap=False, size=10):
    safe_val = _safe(val)
    c = ws.cell(row=row, column=col, value=safe_val)
    if isinstance(safe_val, str):
        c.data_type = 's'
    c.font = Font(name='Arial', bold=bold, color=fg, size=size)
    c.fill = PatternFill('solid', fgColor=bg)
    c.alignment = Alignment(horizontal='center', vertical='center', wrap_text=wrap)
    return c

def cell(ws, row, col, val, bg=None, fg='111827', bold=False, wrap=True, align='left'):
    safe_val = _safe(val)
    c = ws.cell(row=row, column=col, value=safe_val)
    if isinstance(safe_val, str):
        c.data_type = 's'
    c.font = Font(name='Arial', color=fg, bold=bold, size=9)
    if bg: c.fill = PatternFill('solid', fgColor=bg)
    c.alignment = Alignment(horizontal=align, vertical='top', wrap_text=wrap)
    return c

def thin_border(ws, row, col):
    t = Border(
        left=Side(style='thin',color='E2E8F0'),
        right=Side(style='thin',color='E2E8F0'),
        top=Side(style='thin',color='E2E8F0'),
        bottom=Side(style='thin',color='E2E8F0')
    )
    ws.cell(row=row, column=col).border = t

wb = Workbook()

# ═══════════════════════════════════════════════════════════════════════
# SHEET 1: SUMMARY
# ═══════════════════════════════════════════════════════════════════════
ws = wb.active
ws.title = 'Summary'
ws.sheet_view.showGridLines = False
ws.column_dimensions['A'].width = 28
ws.column_dimensions['B'].width = 18
ws.column_dimensions['C'].width = 22
ws.column_dimensions['D'].width = 18

# Title banner
ws.row_dimensions[1].height = 36
ws.merge_cells('A1:D1')
t = ws['A1']
t.value = f"M365 Security Assessment — {meta['TenantDomain']}"
t.font = Font(name='Arial', bold=True, size=16, color=WHITE)
t.fill = PatternFill('solid', fgColor=NAVY)
t.alignment = Alignment(horizontal='center', vertical='center')

ws.merge_cells('A2:D2')
s = ws['A2']
s.value = f"Generated: {meta['AssessmentDate']}  |  Tool: NRG-Assessment v{meta['ToolVersion']}"
s.font = Font(name='Arial', size=9, color='6B7280')
s.alignment = Alignment(horizontal='center')

# Score section
total = len(scoring)
gaps  = sum(1 for f in scoring if f['State']=='Gap')
parts = sum(1 for f in scoring if f['State']=='Partial')
sats  = sum(1 for f in scoring if f['State']=='Satisfied')
nas   = sum(1 for f in scoring if f['State']=='NotApplicable')
# Errors are scored as failures (they sit in the denominator), so the summary
# MUST name them: without the row a reader adds Satisfied + Partial + Gaps,
# comes up short of the stated Assessed count, and cannot tell whether the
# missing rows were passes or failures.
errs  = sum(1 for f in scoring if f['State']=='Error')
scored = total - nas
score  = round(100*(sats+0.5*parts)/scored) if scored else 0
posture = 'Strong' if score>=85 else 'Moderate' if score>=65 else 'At Risk' if score>=40 else 'Critical Risk'

hdr(ws,4,1,'Metric',NAVY,WHITE); hdr(ws,4,2,'Value',NAVY,WHITE); hdr(ws,4,3,'Metric',NAVY,WHITE); hdr(ws,4,4,'Value',NAVY,WHITE)
rows4 = [
    ('Security Score', f'{score}/100', 'Posture', posture),
    ('Total Controls', total,          'Gaps',    gaps),
    ('Satisfied',      sats,           'Partial', parts),
    ('Errors',         errs,           'Not Applicable', nas),
    ('Assessed',       scored,         'Total States', f'{sats}+{parts}+{gaps}+{errs}+{nas}={sats+parts+gaps+errs+nas}'),
]
for i,(l1,v1,l2,v2) in enumerate(rows4,5):
    cell(ws,i,1,l1,LGRAY,NAVY,True)
    cell(ws,i,2,v1,WHITE,'111827',True,align='center')
    cell(ws,i,3,l2,LGRAY,NAVY,True)
    cell(ws,i,4,v2,WHITE,'111827',True,align='center')
    ws.row_dimensions[i].height = 18

# Severity breakdown
ws.merge_cells('A10:D10')
hdr(ws,10,1,'Gap Severity Breakdown',ORANGE,WHITE)
sev_hdr = ['Critical','High','Medium','Low']
for j,s2 in enumerate(sev_hdr,1):
    hdr(ws,11,j,s2,SEV_COLORS[s2],WHITE,size=9)
    cnt = sum(1 for f in scoring if f['State']=='Gap' and f['Severity']==s2)
    cell(ws,12,j,cnt,WHITE,SEV_COLORS[s2],True,align='center')

# Workload scores
ws.merge_cells('A14:D14')
hdr(ws,14,1,'Score by Workload',BLUE,WHITE)
hdr(ws,15,1,'Workload',MGRAY,NAVY); hdr(ws,15,2,'Score',MGRAY,NAVY); hdr(ws,15,3,'Gaps',MGRAY,NAVY); hdr(ws,15,4,'Controls',MGRAY,NAVY)
wl_names={'AAD':'Identity & Access','EXO':'Exchange Online','DNS':'DNS Email Auth','DEF':'Microsoft Defender',
          'SPO':'SharePoint/OneDrive','TMS':'Microsoft Teams','INT':'Intune/Endpoint','PVW':'Purview/Compliance','PPL':'Power Platform'}
from collections import defaultdict
wl_groups = defaultdict(list)
for f in scoring:
    wl = f['ControlId'].split('-')[0]
    wl_groups[wl].append(f)
row=16
for wl in ['AAD','EXO','DEF','DNS','SPO','TMS','INT','PVW','PPL']:
    grp = wl_groups.get(wl,[])
    if not grp: continue
    wn  = sum(1 for f in grp if f['State']!='NotApplicable')
    ws2 = sum(1 for f in grp if f['State']=='Satisfied')
    wp2 = sum(1 for f in grp if f['State']=='Partial')
    wg2 = sum(1 for f in grp if f['State']=='Gap')
    wsc = round(100*(ws2+0.5*wp2)/wn) if wn else 0
    col2= GREEN if wsc>=85 else AMBER if wsc>=65 else 'EA580C' if wsc>=40 else RED
    cell(ws,row,1,wl_names.get(wl,wl),LGRAY,NAVY)
    cell(ws,row,2,f'{wsc}/100',WHITE,col2,True,align='center')
    cell(ws,row,3,wg2,WHITE,RED if wg2>0 else GREEN,True,align='center')
    cell(ws,row,4,len(grp),WHITE,'111827',align='center')
    ws.row_dimensions[row].height = 16
    row+=1

# Framework scores
fws = {'CIS':'CIS M365 v6.0.1','SCuBA':'CISA SCuBA','NIST':'NIST 800-53r5','CMMC':'CMMC 2.0 L2',
       'ISO27001':'ISO 27001:2022','SOC2':'SOC 2','HIPAA':'HIPAA §164','PCIDSS':'PCI DSS v4.0'}
ws.merge_cells(f'A{row+1}:D{row+1}')
hdr(ws,row+1,1,'Framework Compliance',NAVY,WHITE)
hdr(ws,row+2,1,'Framework',MGRAY,NAVY); hdr(ws,row+2,2,'Score',MGRAY,NAVY)
hdr(ws,row+2,3,'Mapped Controls',MGRAY,NAVY); hdr(ws,row+2,4,'Reference',MGRAY,NAVY)
row+=3
for fw, fname in fws.items():
    ff = [f for f in scoring if any(fid.startswith(fw + ':') for fid in f['FrameworkIds'])]
    fd = [f for f in ff if f['State']!='NotApplicable']
    fs = sum(1 for f in fd if f['State']=='Satisfied')
    fp = sum(1 for f in fd if f['State']=='Partial')
    fsc= round(100*(fs+0.5*fp)/len(fd)) if fd else 0
    fcol=GREEN if fsc>=85 else AMBER if fsc>=65 else 'EA580C' if fsc>=40 else RED
    cell(ws,row,1,fname,LGRAY,NAVY); cell(ws,row,2,f'{fsc}%',WHITE,fcol,True,align='center')
    cell(ws,row,3,len(fd),WHITE,'111827',align='center'); cell(ws,row,4,fw,WHITE,DGRAY)
    ws.row_dimensions[row].height=16; row+=1

